pub fn fqcn_for_tag(tag: &str) -> Option<&'static str> {
    TAG_TO_FQCN.iter().find(|(t, _)| *t == tag).map(|(_, f)| *f)
}

pub fn version_for_tag(tag: &str) -> Option<(&'static str, i32)> {
    VERSIONS_BY_TAG_5_4.iter().find(|(t, _, _)| *t == tag).map(|(_, n, v)| (*n, *v))
}

pub fn is_structural_tag(tag: &str) -> bool {
    STRUCTURAL_TAGS.contains(&tag)
}
